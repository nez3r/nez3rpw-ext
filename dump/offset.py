def get_class_block(dump_content, class_name):
    start_pattern = re.compile(r"(class|struct|enum)\s+" + re.escape(class_name) + r"(\s|:|\{)")
    match = start_pattern.search(dump_content)
    
    if not match:
        return ""

    start_index = dump_content.find('{', match.start())
    if start_index == -1:
        return ""

    brace_count = 0
    content_end = -1
    for i in range(start_index, len(dump_content)):
        if dump_content[i] == '{':
            brace_count += 1
        elif dump_content[i] == '}':
            brace_count -= 1
            if brace_count == 0:
                content_end = i
                break
    
    return dump_content[start_index:content_end+1]

def extract_members(class_block):
    lines = class_block.splitlines()
    fields = []
    methods =[]
    
    member_re = re.compile(r"^\s*(.+?)\s*;\s*//\s*(0x[A-Fa-f0-9]+)")

    for line in lines:
        line = line.strip()
        match = member_re.search(line)
        if match:
            sig = match.group(1)
            offset = match.group(2)
            if '(' in sig:
                methods.append({"sig": sig, "off": offset})
            else:
                fields.append({"sig": sig, "off": offset})
                
    return fields, methods

def get_type_info_data(script_data, target_name):
    if not script_data:
        return "Not found", ""

    metadata = script_data.get("ScriptMetadata",[])
    for entry in metadata:
        name = entry.get("Name", "")
        if name == target_name or name.endswith("." + target_name) or name == target_name + "_TypeInfo":
            addr = entry.get("Address", 0)
            return str(addr), hex(addr)
            
    return "Not found", ""

