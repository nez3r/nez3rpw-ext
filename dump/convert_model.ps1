$lines.Add("    ;")
$lines.Add("")
$lines.Add("static const char* const g_model_tri_b64 =")
foreach ($c in (Split-B64 (Ints-To-B64 $triArr))) { $lines.Add("    `"$c`"") }
$lines.Add("    ;")
$lines.Add("")

$sb = [System.Text.StringBuilder]::new()
foreach ($l in $lines) { $sb.Append($l).Append("`n") | Out-Null }
[System.IO.File]::WriteAllText($OutHeader, $sb.ToString())
